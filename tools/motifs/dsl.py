"""Tiny vector DSL for the Bunto motifs. Canvas is 100x100 units.
Everything is original, generated by code -> license free."""
import math

K = 0.5522847498


class P:
    def __init__(self, segs=None):
        self.segs = segs or []

    # ---- transforms -------------------------------------------------
    def map(self, f):
        out = []
        for c, a in self.segs:
            pts = [f(a[i], a[i + 1]) for i in range(0, len(a), 2)]
            out.append((c, [v for p in pts for v in p]))
        return P(out)

    def rot(self, deg, cx=50, cy=50):
        r = math.radians(deg)
        co, si = math.cos(r), math.sin(r)
        return self.map(lambda x, y: (cx + (x - cx) * co - (y - cy) * si,
                                      cy + (x - cx) * si + (y - cy) * co))

    def move(self, dx=0, dy=0):
        return self.map(lambda x, y: (x + dx, y + dy))

    def scale(self, sx, sy=None, cx=50, cy=50):
        sy = sx if sy is None else sy
        return self.map(lambda x, y: (cx + (x - cx) * sx, cy + (y - cy) * sy))

    def flip(self, cx=50):
        return self.map(lambda x, y: (2 * cx - x, y))

    def __add__(self, o):
        return P(self.segs + o.segs)

    def d(self):
        parts = []
        for c, a in self.segs:
            parts.append(c + ("" if not a else " " + " ".join(fmt(v) for v in a)))
        return " ".join(parts)


def fmt(v):
    s = "%.2f" % v
    s = s.rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


# ---- primitives ------------------------------------------------------
def ell(cx, cy, rx, ry=None):
    ry = rx if ry is None else ry
    kx, ky = rx * K, ry * K
    return P([
        ("M", [cx + rx, cy]),
        ("C", [cx + rx, cy + ky, cx + kx, cy + ry, cx, cy + ry]),
        ("C", [cx - kx, cy + ry, cx - rx, cy + ky, cx - rx, cy]),
        ("C", [cx - rx, cy - ky, cx - kx, cy - ry, cx, cy - ry]),
        ("C", [cx + kx, cy - ry, cx + rx, cy - ky, cx + rx, cy]),
        ("Z", []),
    ])


def rpoly(pts, r=0.0):
    """Closed polygon with rounded corners (radius r)."""
    n = len(pts)
    if r <= 0:
        segs = [("M", list(pts[0]))] + [("L", list(p)) for p in pts[1:]] + [("Z", [])]
        return P(segs)
    segs = []
    for i in range(n):
        p0, p1, p2 = pts[i - 1], pts[i], pts[(i + 1) % n]
        v1 = (p0[0] - p1[0], p0[1] - p1[1])
        v2 = (p2[0] - p1[0], p2[1] - p1[1])
        l1, l2 = math.hypot(*v1), math.hypot(*v2)
        rr = min(r, l1 / 2.05, l2 / 2.05)
        a = (p1[0] + v1[0] / l1 * rr, p1[1] + v1[1] / l1 * rr)
        b = (p1[0] + v2[0] / l2 * rr, p1[1] + v2[1] / l2 * rr)
        c1 = (a[0] + (p1[0] - a[0]) * 0.55, a[1] + (p1[1] - a[1]) * 0.55)
        c2 = (b[0] + (p1[0] - b[0]) * 0.55, b[1] + (p1[1] - b[1]) * 0.55)
        segs.append(("M" if i == 0 else "L", list(a)))
        segs.append(("C", [c1[0], c1[1], c2[0], c2[1], b[0], b[1]]))
    segs.append(("Z", []))
    return P(segs)


def rect(x, y, w, h, r=0):
    return rpoly([(x, y), (x + w, y), (x + w, y + h), (x, y + h)], r)


def blob(pts, closed=True, t=0.5):
    """Smooth Catmull-Rom curve through pts."""
    n = len(pts)
    segs = [("M", list(pts[0]))]
    cnt = n if closed else n - 1
    for i in range(cnt):
        p0 = pts[(i - 1) % n] if (closed or i > 0) else pts[i]
        p1 = pts[i]
        p2 = pts[(i + 1) % n]
        p3 = pts[(i + 2) % n] if (closed or i + 2 < n) else p2
        c1 = (p1[0] + (p2[0] - p0[0]) * t / 3 * 2 * 0.5 * 1.0, p1[1] + (p2[1] - p0[1]) * t / 3 * 2 * 0.5 * 1.0)
        c2 = (p2[0] - (p3[0] - p1[0]) * t / 3 * 2 * 0.5 * 1.0, p2[1] - (p3[1] - p1[1]) * t / 3 * 2 * 0.5 * 1.0)
        segs.append(("C", [c1[0], c1[1], c2[0], c2[1], p2[0], p2[1]]))
    if closed:
        segs.append(("Z", []))
    return P(segs)


def curve(pts, t=0.5):
    return blob(pts, closed=False, t=t)


def line(*pts):
    return P([("M", list(pts[0]))] + [("L", list(p)) for p in pts[1:]])


def arc(cx, cy, rx, ry, a0, a1, n=6):
    pts = []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        pts.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return curve(pts)


def star(cx, cy, r1, r2, n=5, rot=-90, round_=0):
    pts = []
    for i in range(n * 2):
        r = r1 if i % 2 == 0 else r2
        a = math.radians(rot + i * 180 / n)
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return rpoly(pts, round_)


def ngon(cx, cy, r, n, rot=-90, round_=0):
    pts = [(cx + r * math.cos(math.radians(rot + i * 360 / n)),
            cy + r * math.sin(math.radians(rot + i * 360 / n))) for i in range(n)]
    return rpoly(pts, round_)


def petal(r0, r1, w, cx=50, cy=50):
    """Teardrop petal pointing up from radius r0 to r1 (width w)."""
    ym, yt = cy - r0, cy - r1
    return P([
        ("M", [cx, ym]),
        ("C", [cx + w, ym - (r1 - r0) * 0.25, cx + w * 0.7, yt + (r1 - r0) * 0.15, cx, yt]),
        ("C", [cx - w * 0.7, yt + (r1 - r0) * 0.15, cx - w, ym - (r1 - r0) * 0.25, cx, ym]),
        ("Z", []),
    ])


def heart(cx, cy, s):
    return P([
        ("M", [cx, cy + s * 0.9]),
        ("C", [cx - s * 1.6, cy - s * 0.1, cx - s * 0.9, cy - s * 1.3, cx, cy - s * 0.4]),
        ("C", [cx + s * 0.9, cy - s * 1.3, cx + s * 1.6, cy - s * 0.1, cx, cy + s * 0.9]),
        ("Z", []),
    ])


def cloud(cx, cy, s=1.0):
    pts = [(-16, 4), (-14, -3), (-6, -4), (-2, -10), (6, -9), (9, -3), (16, -1), (17, 5), (8, 7), (-8, 7)]
    return blob([(cx + x * s, cy + y * s) for x, y in pts], t=0.5)


class Motif:
    def __init__(self, id, de, en):
        self.id, self.de, self.en = id, de, en
        self.regions = []
        self.lines = []
        self.dots = []

    def f(self, *paths):
        for p in paths:
            self.regions.append(p)
        return self

    def sym(self, p):
        """add path and its mirror (about x=50) as two regions"""
        self.regions.append(p)
        self.regions.append(p.flip())
        return self

    def l(self, *paths):
        for p in paths:
            self.lines.append(p)
        return self

    def dot(self, *pts):
        """small solid dark dots (eye pupils, nostrils) - not fillable"""
        for x, y, r in pts:
            self.dots.append(ell(x, y, r, r))
        return self

    def eye(self, x, y, d=4.0, pupil=1.8, dx=0.8, dy=0.2):
        """white eye (fillable) with solid pupil"""
        self.f(ell(x, y, d, d))
        self.dot((x + dx, y + dy, pupil))
        return self

    def to_json(self):
        return {"id": self.id, "de": self.de, "en": self.en,
                "regions": [p.d() for p in self.regions],
                "lines": [p.d() for p in self.lines],
                "dots": [p.d() for p in self.dots]}


def fir(cx, top, bottom, hw, teeth=4, r=1.5):
    """Tannen-Etage: Spitze oben, gezackter Boden."""
    pts = [(cx, top)]
    # rechte Kante mit leichten Absätzen
    for i in range(1, 4):
        t = i / 4
        pts.append((cx + hw * t * 0.92 + (1.5 if i % 2 else 0), top + (bottom - top) * t))
    pts.append((cx + hw, bottom))
    # gezackter Boden von rechts nach links
    n = teeth * 2
    for i in range(1, n):
        x = cx + hw - 2 * hw * i / n
        pts.append((x, bottom - (4 if i % 2 else 0) - 0.0))
    pts.append((cx - hw, bottom))
    for i in range(3, 0, -1):
        t = i / 4
        pts.append((cx - hw * t * 0.92 - (1.5 if i % 2 else 0), top + (bottom - top) * t))
    return rpoly(pts, r)


def annulus(cx, cy, r0, r1, a0, a1, n=6):
    """Ringstück (Winkel in Grad)."""
    outer = [(cx + r1 * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
              cy + r1 * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]
    inner = [(cx + r0 * math.cos(math.radians(a1 - (a1 - a0) * i / n)),
              cy + r0 * math.sin(math.radians(a1 - (a1 - a0) * i / n))) for i in range(n + 1)]
    return rpoly(outer + inner, 0)


def bar(x0, y0, x1, y1, w, r=None):
    """Abgerundeter Balken zwischen zwei Punkten (Äste, Zweige, Stäbe)."""
    L = math.hypot(x1 - x0, y1 - y0)
    ang = math.degrees(math.atan2(y1 - y0, x1 - x0))
    return rect(x0, y0 - w / 2, L, w, w / 2 if r is None else r).rot(ang, x0, y0)
